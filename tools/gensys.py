"""Generate the XENIX 2.1.3 (8086) system call stubs for BCC (cdecl), one module per call,
into the directory given on the command line (default build/sys), for libc.a.
Register convention (verified on XENIX 2.1.3): AX = call number, BX/CX/SI/DI = args 1-4,
near call to the gate at text:0002 (int 5). Carry set on error with AX = errno.
Second result word (for long or paired results) comes back in BX, and the kernel copies it
to DX as well. V7 style, getpid/getuid/getgid also return ppid/euid/egid as that second word
(verified on XENIX 2.1.3 with tests/regdump)."""
# name: (V7 call number, argument count)
CALLS = {
    '_exit': (1, 1), 'read': (3, 3), 'write': (4, 3), 'open': (5, 3), 'close': (6, 1),
    'creat': (8, 2), 'link': (9, 2), 'unlink': (10, 1), 'chdir': (12, 1), 'chmod': (15, 2), 'brk': (17, 1),
    'lseek': (19, 4), 'getpid': (20, 0), 'getuid': (24, 0), 'access': (33, 2),
    'kill': (37, 2), 'dup': (41, 1), 'ioctl': (54, 3),
    '_wait': (7, 0), '_time': (13, 0), '_pipe': (42, 0), 'execve': (59, 3),
    'alarm': (27, 1), 'pause': (29, 0), 'umask': (60, 1), 'nice': (34, 1),
    'getgid': (47, 0), 'setuid': (23, 1), 'setgid': (46, 1), 'utime': (30, 2),
    'chown': (16, 3), 'mknod': (14, 3), 'sync': (36, 0), 'stat': (18, 2), 'fstat': (28, 2),
    'times': (43, 1), '_stime': (25, 2),
}
# name: V7 call number; argument-less calls whose result is the second word (BX)
SECOND = {'getppid': 20, 'geteuid': 24, 'getegid': 47}
REGS = ['bx', 'cx', 'si', 'di']
import os, sys
outdir = sys.argv[1] if len(sys.argv) > 1 else 'build/sys'
os.makedirs(outdir, exist_ok=True)
HEAD = ['! generated by tools/gensys.py; XENIX 2.1.3 system call stub', '', '\t.globl\t__syscal']

def stub(name, num, nargs, ret):
    out = HEAD + [f'\t.globl\t{ret}', '', '\t.text', f'\texport\t_{name}', f'_{name}:',
                  '\tpush\tbp', '\tmov\tbp,sp', '\tpush\tsi', '\tpush\tdi']
    for i in range(nargs):
        out.append(f'\tmov\t{REGS[i]},{4 + 2*i}[bp]')
    out += [f'\tmov\tax,#{num}', '\tcall\t__syscal', f'\tbr\t{ret}', '']
    open(f'{outdir}/{name}.s', 'w').write('\n'.join(out))

for name, (num, nargs) in CALLS.items():
    stub(name, num, nargs, '__sysret')
for name, num in SECOND.items():
    stub(name, num, 0, '__sysrt2')
# shared return paths: carry set -> errno = AX, return -1 (long -1 in DX:AX);
# __sysrt2 returns the second result word (BX) instead of AX
open(f'{outdir}/sysret.s', 'w').write('\n'.join([
    '! generated by tools/gensys.py; common return for the system call stubs', '',
    '\t.globl\t_errno', '', '\t.text',
    '\texport\t__sysrt2', '__sysrt2:', '\tjc\t__sysret', '\tmov\tax,bx',
    '\texport\t__sysret', '__sysret:', '\tjnc\tsysok', '\tmov\t[_errno],ax', '\tmov\tax,#-1', '\tmov\tbx,ax',
    'sysok:', '\tmov\tdx,bx', '\tpop\tdi', '\tpop\tsi', '\tpop\tbp', '\tret', '']))
