"""Generate lib/sys.s: XENIX 2.1.3 (8086) system call stubs for BCC (cdecl).
Register convention (verified on XENIX 2.1.3): AX = call number, BX/CX/SI/DI = args 1-4,
near call to the gate at text:0002 (int 5). Carry set on error with AX = errno.
Second result word (for long or paired results) comes back in BX."""
# name: (V7 call number, argument count)
CALLS = {
    '_exit': (1, 1), 'read': (3, 3), 'write': (4, 3), 'open': (5, 2), 'close': (6, 1),
    'creat': (8, 2), 'link': (9, 2), 'unlink': (10, 1), 'chdir': (12, 1), 'chmod': (15, 2),
    'lseek': (19, 4), 'getpid': (20, 0), 'getuid': (24, 0), 'access': (33, 2),
    'kill': (37, 2), 'dup': (41, 1), 'ioctl': (54, 3),
}
REGS = ['bx', 'cx', 'si', 'di']
out = ['! sys.s - generated by tools/gensys.py; XENIX 2.1.3 system call stubs', '', '\t.globl\t__syscal', '\t.globl\t_errno', '', '\t.text']
for name, (num, nargs) in CALLS.items():
    out += [f'\texport\t_{name}', f'_{name}:', '\tpush\tbp', '\tmov\tbp,sp', '\tpush\tsi', '\tpush\tdi']
    for i in range(nargs):
        out.append(f'\tmov\t{REGS[i]},{4 + 2*i}[bp]')
    out += [f'\tmov\tax,#{num}', '\tcall\t__syscal', '\tbr\tsysret', '']
out += ['! common return: carry set -> errno = AX, return -1 (long -1 in DX:AX)',
        'sysret:', '\tjnc\tsysok', '\tmov\t[_errno],ax', '\tmov\tax,#-1', '\tmov\tbx,ax',
        'sysok:', '\tmov\tdx,bx', '\tpop\tdi', '\tpop\tsi', '\tpop\tbp', '\tret', '']
open('lib/sys.s', 'w').write('\n'.join(out))
